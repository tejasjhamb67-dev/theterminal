import type { Security } from '../core/types';

/**
 * Extended built-in universe: S&P-100-class US equities, global majors
 * (incl. India NSE), ETFs, futures, FX crosses, crypto. Beyond this list,
 * ANY listed symbol resolves through the dynamic market search (dynamic.ts).
 * simBase/simVol only drive the offline simulator; live mode uses real quotes.
 */

type Row = [id: string, name: string, yahoo: string, sector: string, base: number, vol: number, cc?: string, ccy?: string];

const eq = (rows: Row[]): Security[] =>
  rows.map(([id, name, yahoo, sector, base, vol, cc, ccy]) => {
    const parts = id.split(' ');
    return {
      id,
      ticker: parts.slice(0, -1).join(' '),
      yellowKey: parts[parts.length - 1] as Security['yellowKey'],
      kind:
        id.endsWith('Index') ? 'index' :
        id.endsWith('Curncy') ? 'fx' :
        id.endsWith('Comdty') ? 'commodity' :
        id.endsWith('Crypto') ? 'crypto' :
        sector === 'ETF' ? 'etf' : 'stock',
      name,
      yahoo,
      currency: ccy ?? 'USD',
      country: cc ?? (id.includes(' US ') ? 'US' : undefined),
      sector: sector === 'ETF' || sector === '—' ? (sector === 'ETF' ? sector : undefined) : sector,
      simBase: base,
      simVol: vol,
    } as Security;
  });

